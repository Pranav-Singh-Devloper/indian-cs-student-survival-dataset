"""Builds the Kaggle dataset-metadata.json (with per-column descriptions) from DATA_DICTIONARY.md.
Usage: python publish/build_metadata.py <kaggle-user> <out-dir>"""
import json, re, sys
from pathlib import Path
import pandas as pd

root = Path(__file__).resolve().parent.parent
user, out = sys.argv[1], Path(sys.argv[2])
dd = (root / "DATA_DICTIONARY.md").read_text()
students_md, sem_md = dd.split("## `data/semester_records.csv`")

def parse(md):
    desc = {}
    for line in md.splitlines():
        if not line.startswith("|") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3 or cells[0] in ("Column",):
            continue
        for name in re.split(r",\s*", re.sub(r"[`*]", "", cells[0])):
            desc[name.strip()] = re.sub(r"[`*]", "", cells[-1]).strip()
    return desc

sd = parse(students_md)
sm = {}
for line in sem_md.splitlines():
    cells = [c.strip() for c in line.strip("|").split("|")]
    if line.startswith("|") and len(cells) == 2 and cells[0] not in ("Column",) and not line.startswith("|---"):
        sm[re.sub(r"[`*]", "", cells[0])] = re.sub(r"[`*]", "", cells[1])

def fields(csv, desc):
    df = pd.read_csv(csv); res = []
    for c in df.columns:
        t = "string" if df[c].dtype == object else "boolean" if df[c].dtype == bool else "number"
        assert c in desc, f"missing description for {c}"
        res.append({"name": c, "description": desc[c], "type": t})
    return res

meta = json.load(open(root / "publish" / "dataset-metadata.json"))
meta["id"] = f"{user}/desi-cs-student-survival"
meta["expectedUpdateFrequency"] = "never"
meta["description"] = (meta["description"] + "\n\n## Provenance\nEntirely synthetic: generated by `generate_dataset.py` (seed 42, included) from a hand-written causal model "
    "(archetype -> traits -> habits -> semester grades -> skills -> placement). No real person, college or company is represented. "
    "Source code & history: https://github.com/Pranav-Singh-Devloper/desi-cs-student-survival-dataset\n\n"
    "## Notes\n* Placement columns exist only for final-year students (year_of_study == 4).\n* Mess columns are empty for day scholars by design.\n"
    "* Missing values are injected on purpose (MCAR, MAR and structural) for practice.")
res = {r["path"]: r for r in meta["resources"]}
res["students.csv"]["schema"] = {"fields": fields(root / "data/students.csv", sd)}
res["semester_records.csv"]["schema"] = {"fields": fields(root / "data/semester_records.csv", sm)}
res["splits.csv"]["schema"] = {"fields": [{"name": "student_id", "description": "Join key to students.csv", "type": "string"}, {"name": "split", "description": "train or test (80/20, stratified by archetype, seed 2026)", "type": "string"}]}
out.mkdir(exist_ok=True)
json.dump(meta, open(out / "dataset-metadata.json", "w"), indent=2)
print("ok", len(sd), len(sm))
